"""Frozen retrieval labels. Reuses Phase 1 EVAL_CASES; not model-generated."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from app.eval.cases import EVAL_CASES, EvalCase

FIXTURE_PATH = Path(__file__).resolve().parent / "fixtures" / "retrieval_eval_v1.json"
DATASET_VERSION = "retrieval_eval_v1"


def case_segment(case: EvalCase) -> str:
    query = case.query.lower()
    notes = case.notes.lower()
    contexts = case.gold_contexts
    outcomes = case.gold_outcomes
    prefs = case.gold_preferences
    tradeoffs = case.gold_tradeoffs
    if notes.startswith("unsupported") or "luxur" in query or "leather" in query:
        return "value_unsupported"
    if "ethical" in query or "sustainable" in query or "durable" in query:
        return "value_unsupported"
    if "gym" in query or "run" in query or "sport" in query or "sweat" in query:
        return "exercise"
    if "office" in query or "call" in query or "podcast" in query or "mic" in query:
        return "work_calling"
    if "gaming" in query:
        return "work_calling"
    if "commut" in query or "fold" in query or "portable" in query:
        return "commuting_portability"
    if "battery" in query or "endurance" in query or "hours battery" in query:
        return "battery_endurance"
    if "reliab" in query or "repair" in query:
        return "reliability"
    if (
        tradeoffs
        or "more than" in query
        or "rather" in query
        or "not that important" in query
    ):
        return "mixed_tradeoffs"
    if (
        "under $" in query
        or "under a$" in query
        or "budget" in query
        or "cheap" in query
    ) and ("comfort" in query or "quality" in query or "anc" in query):
        return "budget_quality"
    if "comfort" in query or "wear" in query or "hours" in query or "all-day" in query:
        return "extended_comfort"
    if (
        "flight" in query
        or "travel" in query
        or "cabin" in query
        or "sydney" in query
        or "long-haul" in query
        or "long haul" in query
    ):
        return "long_haul_travel"
    if "long_haul_travel" in contexts or "frequent_travel" in contexts:
        return "long_haul_travel"
    if "extended_continuous_use" in contexts or "low_fatigue" in outcomes:
        return "extended_comfort"
    if "commuting" in contexts:
        return "commuting_portability"
    if "comfort" in prefs and "price" in prefs:
        return "mixed_tradeoffs"
    if "battery" in prefs or "long_battery_endurance" in outcomes:
        return "battery_endurance"
    if "reliability" in prefs:
        return "reliability"
    if "sports" in contexts:
        return "exercise"
    if "office" in contexts or "gaming" in contexts:
        return "work_calling"
    if "price" in case.gold_constraint_fields:
        return "budget_quality"
    return "mixed_tradeoffs"


def cases_to_records(cases: list[EvalCase] | None = None) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for case in cases or EVAL_CASES:
        rows.append(
            {
                "query_id": case.id,
                "raw_intent": case.query,
                "gold_constraint_fields": sorted(case.gold_constraint_fields),
                "gold_contexts": sorted(case.gold_contexts),
                "gold_outcomes": sorted(case.gold_outcomes),
                "gold_preferences": sorted(case.gold_preferences),
                "gold_tradeoffs": sorted(case.gold_tradeoffs),
                "relevance": case.relevance,
                "expected_relevant_product_ids": [],
                "notes": case.notes,
                "segment": case_segment(case),
            }
        )
    return rows


def export_fixture(path: Path | None = None) -> Path:
    target = path or FIXTURE_PATH
    target.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "version": DATASET_VERSION,
        "source": "apps/api/app/eval/cases.py",
        "labeling": (
            "Frozen Phase 1 human-authored relevance specs. "
            "Not generated by the embedding model under evaluation. "
            "Relevant product IDs are resolved at eval time against the "
            "seed catalogue after deterministic qualification."
        ),
        "cases": cases_to_records(),
    }
    target.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    return target


def load_fixture(path: Path | None = None) -> dict[str, Any]:
    target = path or FIXTURE_PATH
    if target.is_file():
        payload: dict[str, Any] = json.loads(target.read_text(encoding="utf-8"))
        return payload
    return {
        "version": DATASET_VERSION,
        "source": "apps/api/app/eval/cases.py",
        "cases": cases_to_records(),
    }


if __name__ == "__main__":
    path = export_fixture()
    print(f"wrote {path}")
